/**
 * 지구본과 그 다음 화면 사이의 인계 계약.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * 옮겨 붙이는 사람에게: 이 파일이 두 화면이 합의해야 하는 전부다.
 * ─────────────────────────────────────────────────────────────────────────
 *
 * 지구본은 핀으로 하강하다가 마지막 28%에서 화면이 `HANDOFF_COLOR`로 가득
 * 찬다. 그 색에 완전히 잠긴 순간 `onEnterScenario(id, handoff)`가 불린다.
 * 받는 쪽은 **같은 색에서 시작해** `fadeInMs` 동안 밝아지면 된다.
 *
 * 사람이 알아채는 것은 "잘렸다"가 아니라 "기다렸다"이다. 400ms 전환은 눈에
 * 안 띄지만 목적지가 뜨는 동안 200ms 비면 그건 바로 보인다. 그래서 색보다
 * **미리 띄워두는 것**이 더 중요하다 — 다음 화면이 다른 문서라면 하강이
 * 시작될 때 이미 로드가 걸려 있어야 한다.
 *
 * 이음매를 가리는 것은 셋뿐이다:
 *
 *   1. 배경색이 같을 것 — `HANDOFF_COLOR`
 *   2. 지역 라벨이 같은 자리에 있을 것 — 하나만 제자리에 있어도 눈이
 *      "같은 화면"으로 이어 읽는다. `locale`을 그대로 찍으면 된다
 *   3. 타이밍이 맞을 것 — 하강 `DIVE_MS`, 인계 후 `fadeInMs`
 *
 * 같은 origin의 다른 페이지라면 여기에 CSS View Transitions를 얹어 핀이
 * 실제로 모핑되게 만들 수 있다. 다른 앱이면 색 인계만으로 충분하다.
 */

/** 두 화면이 만나는 색. `--bg`와 같다 — 여기서 어긋나면 인계 순간 번쩍인다. */
export const HANDOFF_COLOR = '#06080d'

/** 받는 쪽이 밝아지는 데 쓸 시간 */
export const HANDOFF_FADE_MS = 300

export type Handoff = {
  /** 이 색에서 시작해 밝아질 것 */
  color: string
  /** 밝아지는 데 쓸 시간(ms) */
  fadeInMs: number
  /**
   * 지역 라벨. 같은 문자열을 같은 화면 위치에 두면 이음매가 거의 사라진다.
   * `localTimeLabel`은 실제 시계가 아니라 서사의 시각이다.
   */
  locale: {
    city: string
    country: string
    localTimeLabel: string
  }
  /** 하강이 끝난 화면상 지점(0..1). 받는 쪽이 초점을 맞추고 싶을 때 쓴다 */
  focus: { x: number; y: number }
}

export type EnterScenario = (id: string, handoff: Handoff) => void
